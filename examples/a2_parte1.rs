use matematica_e_fisica_para_jogos::{vetor2::Vetor2, vetor3::Vetor3};

fn main() {
    let r = || rand::random_range(-5000..5000) as f32 / rand::random_range(1..500) as f32;

    println!("Trabalho A2 - Pedro Militão");
    println!("Soma de vetores");
    println!("2D:");
    let v = Vetor2::new(r(), r());
    let u = Vetor2::new(r(), r());
    print!("v: ");
    v.print();
    print!("u: ");
    u.print();
    print!("v + u: ");
    (v + u).print();
    println!();
    println!("3D:");
    let v = Vetor3::new(r(), r(), r());
    let u = Vetor3::new(r(), r(), r());
    print!("v: ");
    v.print();
    print!("u: ");
    u.print();
    print!("v + u: ");
    (v + u).print();
    println!();

    println!("Subtração de vetores");
    println!("2D:");
    let v = Vetor2::new(r(), r());
    let u = Vetor2::new(r(), r());
    print!("v: ");
    v.print();
    print!("u: ");
    u.print();
    print!("v - u: ");
    (v - u).print();
    println!();
    println!("3D:");
    let v = Vetor3::new(r(), r(), r());
    let u = Vetor3::new(r(), r(), r());
    print!("v: ");
    v.print();
    print!("u: ");
    u.print();
    print!("v - u: ");
    (v - u).print();
    println!();

    println!("Vetor inverso");
    println!("2D:");
    let v = Vetor2::new(r(), r());
    print!("v: ");
    v.print();
    print!("-v: ");
    (-v).print();
    println!();
    println!("3D:");
    let v = Vetor3::new(r(), r(), r());
    print!("v: ");
    v.print();
    print!("-v: ");
    (-v).print();
    println!();

    println!("Multiplicação por escalar");
    println!("2D:");
    let v = Vetor2::new(r(), r());
    let n = r();
    print!("v: ");
    v.print();
    println!("n: {}", n);
    print!("v * n: ");
    (v * n).print();
    println!();
    println!("3D:");
    let v = Vetor3::new(r(), r(), r());
    let n = r();
    print!("v: ");
    v.print();
    println!("n: {}", n);
    print!("v * n: ");
    (v * n).print();
    println!();

    println!("Produto escalar (dot)");
    println!("2D:");
    let v = Vetor2::new(r(), r());
    let u = Vetor2::new(r(), r());
    print!("v: ");
    v.print();
    print!("u: ");
    u.print();
    println!("v . u: {}", v.dot(u));
    println!();
    println!("3D:");
    let v = Vetor3::new(r(), r(), r());
    let u = Vetor3::new(r(), r(), r());
    print!("v: ");
    v.print();
    print!("u: ");
    u.print();
    println!("v . u: {}", v.dot(u));
    println!();

    println!("Produto vetorial (cross)");
    println!("2D:");
    let v = Vetor2::new(r(), r());
    let u = Vetor2::new(r(), r());
    print!("v: ");
    v.print();
    print!("u: ");
    u.print();
    // Para vetores 2D, o produto vetorial vai gerar a coordenada
    // z, sendo então implementado de maneira a apenas retornar
    // o valor dessa coordenada
    println!("v × u: {}", v.cross(u));
    println!("u × v: {}", u.cross(v));
    println!();
    println!("3D:");
    let v = Vetor3::new(r(), r(), r());
    let u = Vetor3::new(r(), r(), r());
    print!("v: ");
    v.print();
    print!("u: ");
    u.print();
    print!("v × u: ");
    v.cross(u).print();
    print!("u × v: ");
    u.cross(v).print();
    println!();

    println!("Projeção");
    println!("2D:");
    let v = Vetor2::new(r(), r());
    let u = Vetor2::new(r(), r());
    print!("v: ");
    v.print();
    print!("u: ");
    u.print();
    print!("v em u: ");
    v.projection(u).print();
    print!("v em u_norm: ");
    v.projection_normalized(u.normalize()).print();
    println!();
    println!("3D:");
    let v = Vetor3::new(r(), r(), r());
    let u = Vetor3::new(r(), r(), r());
    print!("v: ");
    v.print();
    print!("u: ");
    u.print();
    print!("v em u: ");
    v.projection(u).print();
    print!("v em u_norm: ");
    v.projection_normalized(u.normalize()).print();
    println!();

    println!("Deslizar");
    println!("2D:");
    let v = Vetor2::new(r(), r());
    let u = Vetor2::new(r(), r());
    print!("v: ");
    v.print();
    print!("u: ");
    u.print();
    print!("v desliza em u: ");
    v.slide(u, false).print();
    print!("v desliza em u_norm: ");
    v.slide(u.normalize(), true).print();
    println!();
    println!("3D:");
    let v = Vetor3::new(r(), r(), r());
    let u = Vetor3::new(r(), r(), r());
    print!("v: ");
    v.print();
    print!("u: ");
    u.print();
    print!("v desliza em u: ");
    v.slide(u, false).print();
    print!("v desliza em u_norm: ");
    v.slide(u.normalize(), true).print();
    println!();

    println!("Refletir");
    println!("2D:");
    let v = Vetor2::new(r(), r());
    let u = Vetor2::new(r(), r());
    print!("v: ");
    v.print();
    print!("u: ");
    u.print();
    print!("v reflete em u: ");
    v.reflect(u, false).print();
    print!("v reflete em u_norm: ");
    v.reflect(u.normalize(), true).print();
    println!();
    println!("3D:");
    let v = Vetor3::new(r(), r(), r());
    let u = Vetor3::new(r(), r(), r());
    print!("v: ");
    v.print();
    print!("u: ");
    u.print();
    print!("v reflete em u: ");
    v.reflect(u, false).print();
    print!("v reflete em u_norm: ");
    v.reflect(u.normalize(), true).print();
}
